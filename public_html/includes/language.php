/**
 * Translate a key using the current session language.
 * Falls back to English if the key is missing.
 */
function t(string $key): string {
    $lang = $_SESSION['lang'] ?? 'en';
    return $GLOBALS['translations'][$lang][$key]
        ?? $GLOBALS['translations']['en'][$key]
        ?? $key;
}

/**
 * Get the current language code.
 */
function current_lang(): string {
    return $_SESSION['lang'] ?? 'en';
}

/**
 * HTML lang attribute value for the <html> tag.
 */
function html_lang(): string {
    $map = ['en' => 'en', 'zh_hant' => 'zh-Hant', 'zh_hans' => 'zh-Hans'];
    return $map[current_lang()] ?? 'en';
}
